const {chromium}=require(process.env.BIOGEN_PLAYWRIGHT||'playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
(async()=>{const browser=await chromium.launch({channel:'msedge',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const cases=await (await page.request.get('http://127.0.0.1:8765/api/cases')).json();
 const chosen=cases.find(c=>c.id==='000e82439c4b4d1fbcc586feace04fb4');
 assert(chosen,'Existing Tulsi case is required for this verification.');
 await page.goto('http://127.0.0.1:8765/?case='+chosen.id,{waitUntil:'networkidle'});
 await page.locator('[data-step="3"]').click();
 await page.locator('#filterForm button').click();
 await page.waitForFunction(()=>document.querySelectorAll('.compound').length===24&&!document.body.classList.contains('busy'));
 let result=await (await page.request.get('http://127.0.0.1:8765/api/cases/'+chosen.id)).json();
 assert(result.discovery.compounds.length>100);
 assert(!result.discovery.filters.applied);
 assert(result.discovery.compounds.every(c=>c.selected));
 assert.equal(await page.locator('.compound').count(),24);
 assert((await page.locator('.pagination').innerText()).includes(String(result.discovery.compounds.length)));
 await page.locator('#nextCompounds').click();
 assert((await page.locator('.pagination').innerText()).includes('25'));
 await page.locator('#compoundSearch').fill('eugenol');
 await page.locator('#compoundSearch').press('Tab');
 assert(await page.locator('.compound').count()>0);
 const response=await page.request.get('http://127.0.0.1:8765/api/cases/'+chosen.id+'/compounds.csv');
 assert.equal(response.status(),200);
 const csv=await response.text();assert(csv.includes('references'));
 await page.locator('#compoundSearch').fill('');
 await page.locator('#compoundSearch').press('Tab');
 await page.locator('[name="apply_property_filters"]').check();
 await page.locator('[name="max_mw"]').fill('200');
 await page.locator('#filterForm button').click();
 await page.waitForFunction(()=>!document.body.classList.contains('busy'));
 result=await (await page.request.get('http://127.0.0.1:8765/api/cases/'+chosen.id)).json();
 assert(result.discovery.filters.applied);
 assert(result.discovery.compounds.some(c=>!c.selected));
 assert(result.discovery.compounds.length>100);
 // Leave the user's saved case displaying the complete, unfiltered species list.
 await page.locator('[name="apply_property_filters"]').uncheck();
 await page.locator('#filterForm button').click();
 await page.waitForFunction(()=>!document.body.classList.contains('busy'));
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:'docs/process-3-full-database.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 assert.deepEqual(errors,[]);
 fs.writeFileSync('docs/full-compound-interface-verification.json',JSON.stringify({passed:true,case_id:chosen.id,unique_structures:result.discovery.compounds.length,checks:['Full retrieval from saved plant case','No five-record cap','All structures retained with filters off','Pagination','Local compound search','CSV evidence export','Optional filters preserve retrieval','Mobile layout','No JavaScript errors']},null,2));
 console.log('Full compound retrieval verified in browser:',result.discovery.compounds.length);
}finally{await browser.close()}})().catch(e=>{console.error(e);process.exit(1)});
